import { routeStations, type MissionState, type NodeInfo } from "./types.ts";

function node(partial: Partial<NodeInfo> & Pick<NodeInfo, "city" | "country" | "lat" | "lon">): NodeInfo {
  return {
    ttl: null,
    ip: null,
    rttMs: null,
    timedOut: false,
    local: false,
    countryCode: null,
    org: null,
    asn: null,
    ...partial,
  };
}

